export function chooseEnding(stats: StoryStats): keyof typeof endingNodes {
  if (stats.pressure >= 9 && stats.boundaries <= 2) return "exposed";
  if (stats.pressure >= 8 || stats.selfControl <= 1) return "protocol";
  if (stats.boundaries >= 9 && stats.selfControl >= 8 && stats.pressure <= 3) return "subject";
  return "pause";
}

