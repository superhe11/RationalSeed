export type Mood = "corridor" | "chorus" | "laboratory" | "night" | "spring" | "dawn";

export type StoryStats = {
  boundaries: number;
  selfControl: number;
  pressure: number;
};

export type StatDelta = Partial<StoryStats>;

export type Choice = {
  label: string;
  consequence: string;
  next: string;
  delta: StatDelta;
  requires?: Partial<Pick<StoryStats, "boundaries" | "selfControl">> & { pressureMax?: number };
  requiresPath?: { decisions: string[]; minimum: number };
  lockedText?: string;
};

export type StoryNode = {
  id: string;
  chapter: number;
  chapterTitle: string;
  date: string;
  mood: Mood;
  speaker: string;
  text: string;
  aside?: string;
  next?: string;
  choices?: Choice[];
  continueLabel?: string;
};

const c = (
  label: string,
  consequence: string,
  next: string,
  delta: StatDelta,
  requires?: Choice["requires"],
  lockedText?: string,
  requiresPath?: Choice["requiresPath"],
): Choice => ({
  label,
  consequence,
  next,
  delta,
  requires,
  lockedText,
  requiresPath,
});

